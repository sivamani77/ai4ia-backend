from __future__ import annotations

from pathlib import Path
from typing import Any

from app.core.paths import SCRIPTS_DIR, PROJECT_ROOT
from app.pipeline.base import PipelineContext, StageResult, run_script
from app.services.job_store import append_event, load_job, save_job
from app.services.video_job_runner import update_stage, _utc_now

PYTHON_BIN = str(PROJECT_ROOT / ".venv" / "bin" / "python")


def run(job_id: str, request: dict[str, Any], context: PipelineContext) -> StageResult:
    video_path = context.video_path
    update_stage(job_id, "11_subtitles", "running", 10, "Finalizing subtitles")
    append_event(job_id, "stage_started", "11_subtitles", {})

    vp = Path(video_path)
    srt = vp.with_suffix(".srt")
    vtt = vp.with_suffix(".vtt")

    # Step 09 already runs 11 internally; if SRT exists, skip
    if srt.exists() and vtt.exists():
        update_stage(job_id, "11_subtitles", "completed", 100,
                     "Subtitles already generated by Step 09")
        append_event(job_id, "stage_completed", "11_subtitles", {
            "srt_path": str(srt),
            "vtt_path": str(vtt),
            "skipped": True,
        })
        context.srt_path = str(srt)
        context.vtt_path = str(vtt)
        return StageResult(
            stage="11_subtitles",
            status="skipped",
            message="Subtitles already generated by Step 09",
            data={"srt_path": str(srt), "vtt_path": str(vtt)},
        )

    script = SCRIPTS_DIR / "11_generate_final_subtitles.py"
    if not script.exists():
        update_stage(job_id, "11_subtitles", "completed", 100, "Subtitle script not available — skipped")
        append_event(job_id, "stage_completed", "11_subtitles", {"skipped": True})
        return StageResult(
            stage="11_subtitles",
            status="skipped",
            message="Subtitle script not available — skipped",
        )

    cmd = [PYTHON_BIN, str(script), "--video", str(vp), "--model", "small", "--update-manifest"]
    code, stdout, stderr = run_script(job_id, "11_subtitles", cmd)

    if code != 0:
        update_stage(job_id, "11_subtitles", "completed", 100,
                     f"Subtitle generation exited {code} (non-fatal)")
    else:
        update_stage(job_id, "11_subtitles", "completed", 100, "Subtitle finalization complete")

    # Update job paths
    job = load_job(job_id)
    if srt.exists():
        job["paths"]["srt_path"] = str(srt)
    if vtt.exists():
        job["paths"]["vtt_path"] = str(vtt)
    job["updated_at"] = _utc_now()
    save_job(job_id, job)

    append_event(job_id, "stage_completed", "11_subtitles", {
        "srt_path": str(srt) if srt.exists() else None,
        "exit_code": code,
    })

    context.srt_path = str(srt) if srt.exists() else None
    context.vtt_path = str(vtt) if vtt.exists() else None
    return StageResult(
        stage="11_subtitles",
        status="completed",
        message="Subtitle finalization complete" if code == 0 else f"Subtitle generation exited {code} (non-fatal)",
        data={
            "srt_path": str(srt) if srt.exists() else None,
            "vtt_path": str(vtt) if vtt.exists() else None,
            "exit_code": code,
        },
    )
